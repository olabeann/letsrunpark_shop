# Editable text companions, generated from the exact same document content.
def doc_to_md(doc,name):
    lines=[]
    from docx.table import Table
    from docx.text.paragraph import Paragraph
    for child in doc.element.body.iterchildren():
        if child.tag==qn('w:p'):
            para=Paragraph(child,doc)
            if not para.text:continue
            style=para.style.name
            prefix='# ' if style=='Title' else ('## ' if style=='Heading 1' else ('### ' if style=='Heading 2' else ''))
            lines += [prefix+para.text,'']
        elif child.tag==qn('w:tbl'):
            tb=Table(child,doc)
            rows=[[c.text.replace('\n','<br>').replace('|','\\|') for c in r.cells] for r in tb.rows]
            lines += ['| '+' | '.join(rows[0])+' |','| '+' | '.join(['---']*len(rows[0]))+' |']
            lines += ['| '+' | '.join(row)+' |' for row in rows[1:]]
            lines += ['']
    (ROOT/name).write_text('\n'.join(lines),encoding='utf-8')
