def table(doc,headers,rows,widths):
    t=doc.add_table(rows=1,cols=len(headers));t.autofit=False
    for c,w in zip(t.columns,widths):c.width=Cm(w)
    for idx,row in enumerate([headers]+list(rows)):
        cells=t.rows[0].cells if idx==0 else t.add_row().cells
        for j,(c,value) in enumerate(zip(cells,row)):
            c.width=Cm(widths[j]);c.text=str(value)
            pr=c._tc.get_or_add_tcPr()
            borders=OxmlElement('w:tcBorders')
            for side in ['top','left','bottom','right','insideH','insideV']:
                el=OxmlElement('w:'+side);el.set(qn('w:val'),'single');el.set(qn('w:sz'),'4');el.set(qn('w:color'),'D9D9D9');borders.append(el)
            pr.append(borders)
            mar=OxmlElement('w:tcMar')
            for side in ['top','left','bottom','right']:
                el=OxmlElement('w:'+side);el.set(qn('w:w'),'90');el.set(qn('w:type'),'dxa');mar.append(el)
            pr.append(mar)
            sh=OxmlElement('w:shd');sh.set(qn('w:fill'),'173C55' if idx==0 else ('F3F6F8' if idx%2==0 else 'FFFFFF'));pr.append(sh)
            for p in c.paragraphs:
                p.paragraph_format.space_after=Pt(1);p.paragraph_format.line_spacing=1.1
                for r in p.runs:
                    r.font.size=Pt(9);r.font.bold=idx==0
                    if idx==0:r.font.color.rgb=RGBColor(255,255,255)
        if idx==0:
            repeat=OxmlElement('w:tblHeader');t.rows[0]._tr.get_or_add_trPr().append(repeat)
        keep=OxmlElement('w:cantSplit');t.rows[-1]._tr.get_or_add_trPr().append(keep)
    doc.add_paragraph()
    return t

def p(doc,text,label=None):
    par=doc.add_paragraph()
    if label:par.add_run(label+'  ').bold=True
    par.add_run(text)
    return par
def h(doc,text,level=1):doc.add_paragraph(text,'Heading '+str(level))
