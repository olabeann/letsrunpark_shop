def font(n=27,bold=False): return ImageFont.truetype(BOLD if bold else FONT,n)
def text(x,y,s,n=27,bold=False,fill=INK):
    d.multiline_text((x,y),s,font=font(n,bold),fill=fill,spacing=8)
def box(x,y,w,h,title,lines='',kind='new'):
    bg,stroke=COLORS[kind]
    d.rounded_rectangle((x,y,x+w,y+h),radius=16,fill=bg,outline=stroke,width=2)
    text(x+24,y+18,title,30,True)
    if lines: text(x+24,y+61,lines,24)
def arrow(points,label=None,lpos=None,dash=False):
    for a,b in zip(points,points[1:]):
        if dash:
            length=math.dist(a,b)
            for start in range(0,int(length),18):
                t=start/length; u=min(start+10,length)/length
                d.line((a[0]+(b[0]-a[0])*t,a[1]+(b[1]-a[1])*t,a[0]+(b[0]-a[0])*u,a[1]+(b[1]-a[1])*u),fill='#65758a',width=3)
        else: d.line((a,b),fill='#65758a',width=3)
    a,b=points[-2:]; angle=math.atan2(b[1]-a[1],b[0]-a[0])
    d.polygon([b,(b[0]-15*math.cos(angle-.45),b[1]-15*math.sin(angle-.45)),(b[0]-15*math.cos(angle+.45),b[1]-15*math.sin(angle+.45))],fill='#65758a')
    if label and lpos:
        bounds=d.multiline_textbbox(lpos,label,font=font(22),spacing=12)
        d.rectangle((bounds[0]-7,bounds[1]-4,bounds[2]+7,bounds[3]+4),fill='white')
        text(*lpos,label,22)
